#!/usr/bin/env bash
#
# SDD (Spec-Driven Development) на базе OpenSpec — порядок работы над фичей.
#
# Файл носит справочный характер и не предназначен для запуска.
# Команды с префиксом `/` вводятся в чате агента, остальные — в терминале.
#
# Предварительные требования: установленный и авторизованный `glab` (см. README).

# ============================================================
# 1. Анализ pre-spec
# ============================================================

# Передать агенту pre-spec, подготовленный аналитиком.
/opsx:explore

# *** Обсудить спецификацию с агентом: ответить на уточняющие вопросы,   ***
# *** зафиксировать открытые вопросы и допущения.                       ***
# *** На этом этапе артефакты не создаются — только анализ.             ***

# ============================================================
# 2. Создание change и его артефактов
# ============================================================

# Создать change.
/opsx:new post-detail-management

# Сформировать proposal.md — что и зачем делаем.
/opsx:continue

# Сформировать делта-спеку specs/<capability>/spec.md — требования и сценарии.
/opsx:continue

# Сформировать design.md — как реализуем.
/opsx:continue

# Сформировать tasks.md — перечень задач, выводится из design.md.
/opsx:continue

# *** Примечание 1. После каждого continue агента можно попросить            ***
# *** скорректировать созданный артефакт.                                   ***
# ***                                                                       ***
# *** Примечание 2. Команда `/opsx:update` приводит четыре артефакта в       ***
# *** согласованное состояние — например, если design.md был изменён,       ***
# *** а tasks.md не актуализирован.                                         ***
# ***                                                                       ***
# *** Примечание 3. Четыре вызова continue можно заменить одним `/opsx:ff`,  ***
# *** однако в этом случае отсутствует возможность проверить каждый          ***
# *** артефакт до создания следующего. Наибольшее значение имеет проверка    ***
# *** design.md: tasks.md формируется именно на его основе.                 ***

# ============================================================
# 3. Реализация
# ============================================================

# Реализовать задачи из tasks.md.
/opsx:apply

# *** Задачи можно выполнять частями, указав это в том же сообщении,         ***
# *** например: `/opsx:apply — выполнить только задачи 1.1 и 1.2`.           ***
# *** Это даёт возможность проверять результат небольшими порциями.          ***
# ***                                                                       ***
# *** После apply допустимо запрашивать правки, и при необходимости —        ***
# *** актуализировать design.md и tasks.md.                                  ***

# ============================================================
# 4. Верификация
# ============================================================

# Проверить соответствие реализации артефактам change.
# Команда ничего не изменяет — только формирует отчёт.
/opsx:verify

# *** При замечаниях можно повторно вызвать `/opsx:apply` либо описать       ***
# *** требуемую правку словами. Если расхождение вызвано устаревшим планом,  ***
# *** корректировать следует design.md или tasks.md, а не реализацию.        ***

# ============================================================
# 5. Архивация
# ============================================================

# Перенести делта-спеку в openspec/specs/<capability>/spec.md
# и переместить change в openspec/changes/archive/.
# Фича считается закрытой.
/opsx:archive

# Проверить структурную корректность содержимого директории openspec.
# Флаг --all обязателен: после архивации активных change не остаётся,
# и без него команда завершается сообщением «Nothing to validate».
openspec validate --all --strict

# ============================================================
# 6. Отправка изменений
# ============================================================

# Кастомная команда. Выполняет последовательно:
#   - создание ветки (если текущая ветка защищённая либо передан флаг -b);
#   - прогон проверок: prettier, eslint, tsc, тесты;
#   - openspec validate --all --strict;
#   - коммит с привязкой к change через трейлер OpenSpec-Change;
#   - push и создание merge request через glab с назначением на текущего
#     пользователя; описание MR формируется из артефактов change.
/opsx:ship
